LOG = []


def check(i, prefix):
    t = paras[i].text.strip()
    if not t.startswith(prefix):
        raise AssertionError(f'段{i}前缀校验失败: 期望{prefix!r} 实际{t[:50]!r}')


def _first_rpr(pel):
    """取段落内首个run的rPr(字符格式), 无则None"""
    for child in pel.iter(qn('w:r')):
        rpr = child.find(qn('w:rPr'))
        if rpr is not None:
            return copy.deepcopy(rpr)
    return None


def rewrite(i, new_text, prefix):
    """整段重写: 保留段落样式(pPr)与原首run字符格式"""
    check(i, prefix)
    p = paras[i]
    pel = p._p
    rpr = _first_rpr(pel)
    for child in list(pel):
        if child.tag != qn('w:pPr'):
            pel.remove(child)
    r = p.add_run(new_text)
    if rpr is not None:
        r._r.insert(0, rpr)
    LOG.append(f'[重写] 段{i} ({new_text[:24]}...)')


def run_replace(i, pairs, prefix):
    """含公式段落: 仅在run文本内做最小替换, OMML公式不受影响"""
    check(i, prefix)
    p = paras[i]
    for old, new in pairs:
        if not any(old in r.text for r in p.runs):
            raise AssertionError(f'段{i}替换项缺失或跨run: {old!r} | 全文: {p.text}')
    for run in p.runs:
        t = run.text
        for old, new in pairs:
            t = t.replace(old, new)
        run.text = t
    LOG.append(f'[run替换] 段{i}: ' + '; '.join(o for o, _ in pairs))


def insert_after(i, text, prefix, tpl_idx):
    """在段i后插入新段落(样式取模板段tpl_idx)"""
    check(i, prefix)
    tpl = paras[tpl_idx]._p
    rpr = _first_rpr(tpl)
    new_p = copy.deepcopy(tpl)
    for child in list(new_p):
        if child.tag != qn('w:pPr'):
            new_p.remove(child)
    paras[i]._p.addnext(new_p)
    np = Paragraph(new_p, paras[i]._parent)
    r = np.add_run(text)
    if rpr is not None:
        r._r.insert(0, rpr)
    LOG.append(f'[插入] 段{i}后: ({text[:24]}...)')


def set_cell(cell, new_text):
    """表格单元格文本更新, 保留段落样式与首run格式"""
    for extra in cell.paragraphs[1:]:
        extra._p.getparent().remove(extra._p)
    para = cell.paragraphs[0]
    pel = para._p
    rpr = _first_rpr(pel)
    for child in list(pel):
        if child.tag != qn('w:pPr'):
            pel.remove(child)
    r = para.add_run(new_text)
    if rpr is not None:
        r._r.insert(0, rpr)


